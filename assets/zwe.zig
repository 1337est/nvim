//! ZWE (Zig Workspace Engine): reusable source analysis with a Neovim adapter.
//! Zig 0.17.0; Linux; no external Zig or Lua packages.
//! Build: zig build-exe assets/zwe.zig -O safe -femit-bin=zig-out/bin/zwe
//! Test:  zig test assets/zwe.zig
//! Lua:   zwe --print-lua > ~/.config/nvim/lua/zwe.lua
//!
//! Protocol 1: little-endian 16-byte Header; response bodies start with Status:u32.
//! Revisions and offsets refer to Neovim's LF representation, including a final LF.
//! Existing opcodes are unchanged. Optional 14: formatting (capability 32); 15: graph state (64).
//! Parsing uses std.zig.Ast; no custom lexer, incremental parser, or semantic backend.
//! Build refresh executes build.zig configuration, but requests no build/install step.
//! Only use build_graph=true for projects whose build scripts you trust.
//! Graph configuration runs in an isolated worker; publication occurs on the workspace owner thread.

const std = @import("std");
const builtin = @import("builtin");
const Allocator = std.mem.Allocator;
const Io = std.Io;
const Reader = Io.Reader;
const Writer = Io.Writer;
const Ast = std.zig.Ast;
const Node = Ast.Node.Index;
const Token = Ast.TokenIndex;
const Path = Io.Dir.path;

pub const Info = struct {
    pub const zwe_version = "0.1.0";
    pub const zig_version = "0.17.0";
    pub const neovim_version = "0.12.6";
    pub const protocol_version: u32 = 1;
    pub const max_body: usize = 32 * 1024 * 1024;
    pub const max_source: usize = 16 * 1024 * 1024;
    pub const max_source_total: usize = 128 * 1024 * 1024;
    pub const max_documents: usize = 256;
    pub const max_results: usize = 256;
    pub const max_symbols: usize = 4096;
    pub const graph_timeout_ms: u32 = 120_000;

    fn printVersion(w: *Writer) !void {
        try w.print("ZWE {s} (Zig {s}, protocol {d})\n", .{ zwe_version, zig_version, protocol_version });
    }
    fn printLuaClient(w: *Writer) !void {
        try w.print("-- ZWE {s}; Neovim {s}; generated by --print-lua.\n" ++
            "local PROTOCOL_VERSION = {d}\n" ++
            "local MAX_U32, MAX_BODY, MAX_SOURCE = {d}, {d}, {d}\n", .{
            zwe_version,          neovim_version, protocol_version,
            std.math.maxInt(u32), max_body,       max_source,
        });
    }
};

const Op = enum(u16) {
    hello = 1,
    open = 2,
    replace = 3,
    close = 4,
    definition = 5,
    completion = 6,
    symbols = 7,
    diagnostics = 8,
    resync_required = 9,
    protocol_error = 10,
    status = 11,
    shutdown = 12,
    refresh_graph = 13,
    format = 14,
    graph_state = 15,
    fn printLuaClient(w: *Writer) !void {
        try luaEnum(w, "OP", @This());
    }
    fn isQuery(op: Op) bool {
        return switch (op) {
            .definition, .completion, .symbols, .diagnostics, .format => true,
            else => false,
        };
    }
};
const Status = enum(u32) {
    ok,
    not_found,
    unsupported,
    stale_revision,
    invalid_request,
    internal_error,
    ambiguous,
    fn printLuaClient(w: *Writer) !void {
        try luaEnum(w, "STATUS", @This());
    }
    fn fromError(err: anyerror) Status {
        return switch (err) {
            error.StaleRevision, error.MissingDocument => .stale_revision,
            error.DefinitionNotFound, error.ImportNotFound, error.FileNotFound => .not_found,
            error.CompilerSemanticsRequired, error.BuildGraphUnavailable, error.UnknownModuleContext, error.GeneratedModuleUnavailable, error.ModuleRootUnavailable, error.ImportCycleOrTooDeep => .unsupported,
            error.AmbiguousImport, error.DuplicateBufferPath => .ambiguous,
            error.EndOfStream, error.BadFrame, error.InvalidEdit, error.InvalidOffset, error.InvalidPath, error.UnknownOpcode, error.HandshakeRequired, error.ProtocolVersionMismatch, error.FileTooLarge, error.WorkspaceTooLarge, error.TooManyDocuments, error.SyntaxErrors => .invalid_request,
            else => .internal_error,
        };
    }
};
const Capability = enum(u32) {
    definition = 1,
    completion = 2,
    symbols = 4,
    diagnostics = 8,
    build_graph = 16,
    format = 32,
    async_graph = 64,
    const all: u32 = blk: {
        var mask: u32 = 0;
        for (@typeInfo(@This()).@"enum".field_values) |v| mask |= v;
        break :blk mask;
    };
    fn printLuaClient(w: *Writer) !void {
        try luaEnum(w, "CAP", @This());
    }
};
fn luaEnum(w: *Writer, comptime name: []const u8, comptime E: type) !void {
    try w.writeAll("local " ++ name ++ " = {\n");
    const fields = @typeInfo(E).@"enum";
    inline for (fields.field_names, fields.field_values) |key, value|
        try w.print("  {s} = {d},\n", .{ key, value });
    try w.writeAll("}\n");
}

const Header = extern struct {
    body_len: u32,
    request_id: u32,
    document_id: u32,
    opcode: u16,
    flags: u16,
    comptime {
        std.debug.assert(@sizeOf(@This()) == 16);
        std.debug.assert(std.meta.hasUniqueRepresentation(@This()));
    }
    fn decode(bytes: *const [16]u8) Header {
        var r: Reader = .fixed(bytes);
        return r.takeStruct(Header, .little) catch unreachable;
    }
    fn encode(h: Header) [16]u8 {
        var bytes: [16]u8 = undefined;
        var w: Writer = .fixed(&bytes);
        w.writeStruct(h, .little) catch unreachable;
        return bytes;
    }
};
fn words(w: *Writer, values: anytype) !void {
    inline for (values) |v| try w.writeInt(u32, @intCast(v), .little);
}
fn endOfBody(r: *Reader) !void {
    if (r.bufferedLen() != 0) return error.BadFrame;
}
fn endOfToken(ast: *const Ast, token: Ast.TokenIndex) u32 {
    return ast.tokenStart(token) + @as(u32, @intCast(ast.tokenSlice(token).len));
}
fn literalName(gpa: Allocator, raw: []const u8) !?[]const u8 {
    if (raw.len < 2 or raw[0] != '"' or raw[raw.len - 1] != '"') return null;
    if (std.mem.findScalar(u8, raw, '\\') == null) return raw[1 .. raw.len - 1];
    return std.zig.string_literal.parseAlloc(gpa, raw) catch |err| switch (err) {
        error.InvalidLiteral => null,
        else => return err,
    };
}
fn canonicalPath(gpa: Allocator, io: Io, root: []const u8, raw: []const u8) ![:0]u8 {
    if (std.mem.findScalar(u8, raw, 0) != null) return error.InvalidPath;
    const absolute = try Path.resolve(gpa, &.{ root, raw });
    defer gpa.free(absolute);
    return Io.Dir.realPathFileAbsoluteAlloc(io, absolute, gpa) catch |err| switch (err) {
        error.FileNotFound => try gpa.dupeSentinel(u8, absolute, 0),
        else => return err,
    };
}

pub const Document = struct {
    gpa: Allocator,
    id: u32,
    revision: u32,
    path: []u8,
    bytes: std.ArrayList(u8), // Includes an owned trailing NUL, excluded by source().
    ast: ?Ast = null,
    index: ?Index = null, // Borrows ast; invalidate before releasing or moving source.
    disk_stat: ?Io.File.Stat = null,
    checked_request: u64 = 0,
    parse_count: u64 = 0,
    index_count: u64 = 0,

    pub fn init(gpa: Allocator, id: u32, revision: u32, path: []const u8, text: []const u8) !Document {
        if (text.len > Info.max_source) return error.FileTooLarge;
        const name = try gpa.dupe(u8, path);
        errdefer gpa.free(name);
        var bytes: std.ArrayList(u8) = .empty;
        errdefer bytes.deinit(gpa);
        try bytes.appendSlice(gpa, text);
        try bytes.append(gpa, 0);
        return .{ .gpa = gpa, .id = id, .revision = revision, .path = name, .bytes = bytes };
    }
    pub fn deinit(d: *Document) void {
        d.invalidate();
        d.bytes.deinit(d.gpa);
        d.gpa.free(d.path);
    }
    pub fn source(d: *const Document) [:0]const u8 {
        return d.bytes.items[0 .. d.bytes.items.len - 1 :0];
    }
    pub fn invalidate(d: *Document) void {
        if (d.index) |*idx| idx.deinit();
        d.index = null;
        if (d.ast) |*ast| ast.deinit(d.gpa);
        d.ast = null;
    }
    pub fn ensureAst(d: *Document) !*const Ast {
        if (d.ast == null) {
            d.ast = try Ast.parse(d.gpa, d.source(), .{ .mode = .zig, .recover = true });
            d.parse_count += 1;
        }
        return &d.ast.?;
    }
    pub fn ensureIndex(d: *Document) !*Index {
        if (d.index == null) {
            d.index = try Index.init(d.gpa, try d.ensureAst());
            d.index_count += 1;
        }
        return &d.index.?;
    }
    pub fn edit(d: *Document, base: u32, next: u32, start: u32, deleted: u32, inserted: []const u8) !void {
        if (base != d.revision or base == std.math.maxInt(u32) or next != base + 1) return error.StaleRevision;
        const len = d.source().len;
        if (start > len or deleted > len - start) return error.InvalidEdit;
        if (inserted.len > Info.max_source or len - deleted > Info.max_source - inserted.len) return error.FileTooLarge;
        d.invalidate();
        try d.bytes.replaceRange(d.gpa, start, deleted, inserted);
        d.revision = next;
    }
};

// Match the editor representation for unopened UTF-8 files. Mixed LF/CRLF files
// retain CR bytes, like Neovim's default unix,dos detection. No global trim.
fn normalizeSource(gpa: Allocator, raw: []const u8) ![]u8 {
    var bytes: std.ArrayList(u8) = .empty;
    errdefer bytes.deinit(gpa);
    try bytes.ensureTotalCapacity(gpa, raw.len + 1);
    var has_lf = false;
    var dos = true;
    for (raw, 0..) |c, i| if (c == '\n') {
        has_lf = true;
        if (i == 0 or raw[i - 1] != '\r') dos = false;
    };
    var i: usize = if (std.mem.startsWith(u8, raw, "\xef\xbb\xbf")) 3 else 0;
    while (i < raw.len) : (i += 1) {
        if (dos and has_lf and raw[i] == '\r' and i + 1 < raw.len and raw[i + 1] == '\n') continue;
        bytes.appendAssumeCapacity(raw[i]);
    }
    if (bytes.items.len == 0 or bytes.items[bytes.items.len - 1] != '\n') bytes.appendAssumeCapacity('\n');
    return bytes.toOwnedSlice(gpa);
}

/// Owner-thread API. Root/toolchain/options are borrowed until deinit().
/// Call beginRequest() before a query group to publish completed graph jobs and
/// advance disk-cache validation. Destroy request arenas before mutating documents.
/// A document with a built index must stay at a stable address (the index borrows its AST).
pub const Workspace = struct {
    gpa: Allocator,
    io: Io,
    root: []const u8,
    zig_exe: []const u8,
    build_options: []const []const u8,
    graph: BuildGraph,
    graph_ready: bool = false,
    graph_error: ?anyerror = null,
    docs: std.ArrayList(*Document) = .empty,
    graph_job: ?*GraphJob = null,
    graph_generation: u32 = 0,
    requests: u64 = 0,
    edits: u64 = 0,
    bytes_received: u64 = 0,

    pub fn init(gpa: Allocator, io: Io, root: []const u8, zig_exe: []const u8, options: []const []const u8) Workspace {
        return .{ .gpa = gpa, .io = io, .root = root, .zig_exe = zig_exe, .build_options = options, .graph = BuildGraph.init(gpa, io) };
    }
    pub fn deinit(s: *Workspace) void {
        s.cancelGraph();
        for (s.docs.items) |d| {
            d.deinit();
            s.gpa.destroy(d);
        }
        s.docs.deinit(s.gpa);
        s.graph.deinit();
    }
    fn totalBytes(s: *const Workspace) usize {
        var n: usize = 0;
        for (s.docs.items) |d| n += d.source().len;
        return n;
    }
    pub fn beginRequest(s: *Workspace) void {
        s.requests += 1;
        s.pollGraph();
    }
    pub fn findId(s: *Workspace, id: u32) ?*Document {
        if (id != 0) for (s.docs.items) |d| {
            if (d.id == id) return d;
        };
        return null;
    }
    pub fn findPath(s: *Workspace, path: []const u8) ?*Document {
        var cached: ?*Document = null;
        for (s.docs.items) |d| if (std.mem.eql(u8, d.path, path)) {
            if (d.id != 0) return d;
            cached = d;
        };
        return cached;
    }
    fn removeAt(s: *Workspace, i: usize) void {
        const d = s.docs.swapRemove(i);
        d.deinit();
        s.gpa.destroy(d);
    }
    pub fn open(s: *Workspace, document_id: u32, rev: u32, raw_path: []const u8, source: []const u8) !void {
        if (document_id == 0 or rev == 0 or raw_path.len == 0 or !Path.isAbsolute(raw_path)) return error.BadFrame;
        const path = try canonicalPath(s.gpa, s.io, s.root, raw_path);
        defer s.gpa.free(path);
        var replaced_bytes: usize = 0;
        var replaced_count: usize = 0;
        for (s.docs.items) |d| {
            const same_path = std.mem.eql(u8, d.path, path);
            if (same_path and d.id != 0 and d.id != document_id) return error.DuplicateBufferPath;
            if (d.id == document_id or same_path) {
                replaced_bytes += d.source().len;
                replaced_count += 1;
            }
        }
        if (source.len > Info.max_source) return error.FileTooLarge;
        if (s.totalBytes() - replaced_bytes + source.len > Info.max_source_total) return error.WorkspaceTooLarge;
        if (s.docs.items.len - replaced_count >= Info.max_documents) return error.TooManyDocuments;
        const fresh = try s.gpa.create(Document);
        errdefer s.gpa.destroy(fresh);
        fresh.* = try Document.init(s.gpa, document_id, rev, path, source);
        errdefer fresh.deinit();
        try s.docs.ensureUnusedCapacity(s.gpa, 1);
        var i: usize = 0;
        while (i < s.docs.items.len) {
            const d = s.docs.items[i];
            if (d.id == document_id or std.mem.eql(u8, d.path, path)) s.removeAt(i) else i += 1;
        }
        s.docs.appendAssumeCapacity(fresh);
    }
    pub fn replace(s: *Workspace, document_id: u32, base: u32, next: u32, start: u32, deleted: u32, inserted: []const u8) !void {
        const d = s.findId(document_id) orelse return error.MissingDocument;
        if (start > d.source().len or deleted > d.source().len - start) return error.InvalidEdit;
        if (inserted.len > Info.max_source or s.totalBytes() - deleted + inserted.len > Info.max_source_total) return error.WorkspaceTooLarge;
        try d.edit(base, next, start, deleted, inserted);
        s.edits += 1;
    }
    pub fn loadPath(s: *Workspace, raw_path: []const u8) !*Document {
        const path = try canonicalPath(s.gpa, s.io, s.root, raw_path);
        defer s.gpa.free(path);
        const existing = s.findPath(path);
        if (existing) |d| if (d.id != 0 or d.checked_request == s.requests) return d;
        const file = try Io.Dir.openFileAbsolute(s.io, path, .{});
        defer file.close(s.io);
        const stat = try file.stat(s.io);
        if (stat.kind != .file) return error.NotSourceFile;
        if (stat.size > Info.max_source) return error.FileTooLarge;
        if (existing) |d| if (d.disk_stat) |old| {
            if (old.inode == stat.inode and old.size == stat.size and
                old.mtime.nanoseconds == stat.mtime.nanoseconds and old.ctime.nanoseconds == stat.ctime.nanoseconds)
            {
                d.checked_request = s.requests;
                return d;
            }
        };
        var reader = file.reader(s.io, &.{});
        const raw = try reader.interface.allocRemaining(s.gpa, .limited(Info.max_source + 1));
        defer s.gpa.free(raw);
        const text = try normalizeSource(s.gpa, raw);
        defer s.gpa.free(text);
        const old_size = if (existing) |d| d.source().len else 0;
        if (s.totalBytes() - old_size + text.len > Info.max_source_total) return error.WorkspaceTooLarge;
        if (existing == null and s.docs.items.len >= Info.max_documents) return error.TooManyDocuments;
        var fresh = try Document.init(s.gpa, 0, 0, path, text);
        errdefer fresh.deinit();
        fresh.disk_stat = stat;
        fresh.checked_request = s.requests;
        if (existing) |d| {
            d.deinit();
            d.* = fresh;
            return d;
        }
        const d = try s.gpa.create(Document);
        errdefer s.gpa.destroy(d);
        d.* = fresh;
        try s.docs.append(s.gpa, d);
        return d;
    }
    pub fn importDocument(s: *Workspace, from: *Document, name: []const u8) !*Document {
        if (std.mem.eql(u8, name, "builtin")) return error.CompilerSemanticsRequired;
        if (std.mem.endsWith(u8, name, ".zig")) {
            const path = try Path.resolve(s.gpa, &.{ Path.dirname(from.path) orelse s.root, name });
            defer s.gpa.free(path);
            const target = try s.loadPath(path);
            if (s.graph_ready) try s.graph.noteFileImport(from.path, target.path);
            return target;
        }
        if (!s.graph_ready) return error.BuildGraphUnavailable;
        return s.loadPath(try s.graph.resolveImport(from.path, name) orelse return error.ImportNotFound);
    }
    const Target = struct { doc: *Document, decl: ?u32 = null };
    fn followImport(s: *Workspace, from: *Document, ref: Index.ImportRef, depth: usize) anyerror!Target {
        if (depth >= 24) return error.ImportCycleOrTooDeep;
        var target: Target = .{ .doc = try s.importDocument(from, ref.path) };
        for (ref.members[0..ref.member_count], 0..) |name, i| {
            const idx = try target.doc.ensureIndex();
            const result = if (target.decl) |id|
                (if (ref.instance_after != null and @as(usize, ref.instance_after.?) == i) idx.memberAsInstance(id, name) else idx.member(id, name))
            else
                idx.exported(name);
            target = switch (result) {
                .local => |id| .{ .doc = target.doc, .decl = id },
                .import => |next| try s.followImport(target.doc, next, depth + 1),
                .not_found => return error.DefinitionNotFound,
                .unsupported => return error.CompilerSemanticsRequired,
            };
        }
        return target;
    }
    pub fn document(s: *Workspace, id: u32, revision: u32) !*Document {
        const d = s.findId(id) orelse return error.MissingDocument;
        if (revision != d.revision) return error.StaleRevision;
        return d;
    }
    pub fn close(s: *Workspace, id: u32) void {
        for (s.docs.items, 0..) |d, i| if (d.id == id) {
            s.removeAt(i);
            return;
        };
    }
    pub const Location = struct {
        revision: u32,
        document_id: u32,
        target_revision: u32,
        first: u32,
        last: u32,
        path: []const u8,
    };
    // Returned paths/labels borrow document state; consume them before the next edit.
    pub fn definition(s: *Workspace, d: *Document, offset: u32) !Location {
        if (offset > d.source().len) return error.InvalidOffset;
        const idx = try d.ensureIndex();
        const target: Target = switch (idx.definition(offset)) {
            .local => |id| .{ .doc = d, .decl = id },
            .import => |ref| try s.followImport(d, ref, 0),
            .not_found => return error.DefinitionNotFound,
            .unsupported => return error.CompilerSemanticsRequired,
        };
        var first: u32 = 0;
        var last: u32 = 0;
        if (target.decl) |id| {
            const decl = (try target.doc.ensureIndex()).decls.items[id];
            first = decl.start;
            last = decl.end;
        }
        return .{ .revision = d.revision, .document_id = target.doc.id, .target_revision = target.doc.revision, .first = first, .last = last, .path = target.doc.path };
    }
    pub const Item = struct { kind: u32, label: []const u8, detail: []const u8, insert: []const u8 };
    pub const Completion = struct { revision: u32, first: u32, last: u32, items: []const Item };
    // The request allocator owns the list; names may borrow the current source/index.
    pub fn completion(s: *Workspace, a: Allocator, d: *Document, offset: u32) !Completion {
        if (offset > d.source().len) return error.InvalidOffset;
        const idx = try d.ensureIndex();
        const c = try idx.complete(a, offset, Info.max_results);
        if (c.unsupported) return error.CompilerSemanticsRequired;
        var owner = idx;
        var ids = c.ids;
        if (c.import_ref) |ref| {
            var resolved = try s.followImport(d, ref, 0);
            var as_instance = ref.instance_after != null and ref.instance_after.? == ref.member_count;
            var redirects: usize = 0;
            while (resolved.decl) |id| {
                if (redirects >= 24) return error.ImportCycleOrTooDeep;
                owner = try resolved.doc.ensureIndex();
                switch (owner.completionTarget(id, as_instance)) {
                    .local => break,
                    .import => |next| {
                        resolved = try s.followImport(resolved.doc, next, redirects + 1);
                        as_instance = next.instance_after != null and next.instance_after.? == next.member_count;
                    },
                    else => return error.CompilerSemanticsRequired,
                }
                redirects += 1;
            }
            owner = try resolved.doc.ensureIndex();
            ids = try owner.members(a, resolved.decl, as_instance, c.prefix, Info.max_results);
        }
        var items: std.ArrayList(Item) = .empty;
        const quoted = c.replace_start >= 2 and std.mem.eql(u8, d.source()[c.replace_start - 2 .. c.replace_start], "@\"");
        for (ids) |id| {
            const decl = owner.decls.items[id];
            const raw = owner.ast.tokenSlice(decl.token);
            const insertion = if (quoted and std.mem.startsWith(u8, raw, "@\"")) raw[2 .. raw.len - 1] else raw;
            try items.append(a, .{ .kind = wireKind(decl.kind), .label = decl.name, .detail = @tagName(decl.kind), .insert = insertion });
        }
        if (c.mode == .builtin) {
            for (std.zig.BuiltinFn.list.keys(), std.zig.BuiltinFn.list.values()) |name, spec| {
                if (!std.mem.startsWith(u8, name, c.prefix)) continue;
                const detail = if (spec.param_count) |n| try std.fmt.allocPrint(a, "builtin ({d} arguments)", .{n}) else "builtin (variadic)";
                try appendItem(a, &items, .{ .kind = 1, .label = name, .detail = detail, .insert = name });
            }
        } else if (c.mode == .lexical and !quoted) {
            for (std.zig.Token.keywords.keys()) |name| if (std.mem.startsWith(u8, name, c.prefix)) {
                try appendItem(a, &items, .{ .kind = 6, .label = name, .detail = "keyword", .insert = name });
            };
            for (std.zig.primitives.names.keys()) |name| if (std.mem.startsWith(u8, name, c.prefix)) {
                try appendItem(a, &items, .{ .kind = 8, .label = name, .detail = "primitive", .insert = name });
            };
            // Integer types are an open family, intentionally absent from primitives.names.
            inline for (.{ "u8", "u16", "u32", "u64", "u128", "i8", "i16", "i32", "i64", "i128" }) |name| {
                if (std.mem.startsWith(u8, name, c.prefix)) try appendItem(a, &items, .{ .kind = 8, .label = name, .detail = "integer type", .insert = name });
            }
        }
        return .{ .revision = d.revision, .first = c.replace_start, .last = offset, .items = items.items };
    }
    fn appendItem(a: Allocator, items: *std.ArrayList(Item), item: Item) !void {
        if (items.items.len >= Info.max_results) return;
        for (items.items) |old| if (std.mem.eql(u8, old.insert, item.insert)) return;
        try items.append(a, item);
    }
    pub const Symbol = struct { first: u32, last: u32, kind: u32, name: []const u8 };
    pub fn symbols(_: *Workspace, a: Allocator, d: *Document) ![]const Symbol {
        const ast = try d.ensureAst();
        var list: std.ArrayList(Symbol) = .empty;
        for (ast.rootDecls()) |node| {
            if (list.items.len == Info.max_symbols) break;
            var one: [1]Ast.Node.Index = undefined;
            const token: Ast.TokenIndex, const kind: u32 = if (ast.fullVarDecl(node)) |v|
                .{ v.ast.mut_token + 1, if (ast.tokenTag(v.ast.mut_token) == .keyword_const) 3 else 2 }
            else if (ast.fullFnProto(&one, node)) |f| .{ f.name_token orelse continue, 1 } else if (ast.fullContainerField(node)) |f| (if (f.ast.tuple_like) continue else .{ f.ast.main_token, 4 }) else continue;
            if (token >= ast.tokens.len or ast.tokenTag(token) != .identifier) continue;
            const raw = ast.tokenSlice(token);
            const name = if (std.mem.startsWith(u8, raw, "@\"")) (try literalName(a, raw[1..]) orelse continue) else raw;
            if (std.mem.eql(u8, name, "_")) continue;
            try list.append(a, .{ .first = ast.tokenStart(token), .last = endOfToken(ast, token), .kind = kind, .name = name });
        }
        return list.items;
    }
    pub const Diagnostic = struct { first: u32, last: u32, severity: u32, message: []const u8 };
    pub fn diagnostics(_: *Workspace, a: Allocator, d: *Document) ![]const Diagnostic {
        const ast = try d.ensureAst();
        const count = @min(ast.errors.len, Info.max_results);
        var list: std.ArrayList(Diagnostic) = .empty;
        var message: Writer.Allocating = .init(a);
        defer message.deinit();
        for (ast.errors[0..count]) |err| {
            message.clearRetainingCapacity();
            try ast.renderError(err, &message.writer);
            const first: u32 = @intCast(@min(ast.source.len, ast.tokenStart(err.token) + ast.errorOffset(err)));
            const last = @min(@as(u32, @intCast(ast.source.len)), @max(first, endOfToken(ast, err.token)));
            try list.append(a, .{ .first = first, .last = last, .severity = if (err.is_note) 3 else 1, .message = try a.dupe(u8, message.written()) });
        }
        return list.items;
    }
    pub fn format(_: *Workspace, a: Allocator, d: *Document) ![]const u8 {
        const ast = try d.ensureAst();
        if (ast.errors.len != 0) return error.SyntaxErrors;
        const text = try ast.renderAlloc(a);
        if (text.len > Info.max_source or text.len + 8 > Info.max_body) return error.FileTooLarge;
        return text;
    }
    pub fn writeStatus(s: *Workspace, w: *Writer) !void {
        var parses: u64 = 0;
        var indexes: u64 = 0;
        var live: usize = 0;
        for (s.docs.items) |d| {
            parses += d.parse_count;
            indexes += d.index_count;
            live += @intFromBool(d.id != 0);
        }
        try Info.printVersion(w);
        try w.print("Root: {s}\nDocuments: {d} open, {d} cached; source bytes: {d}\n" ++
            "Requests: {d}; edits: {d}; parses: {d}; indexes: {d}; received: {d} bytes\n", .{
            s.root, live, s.docs.items.len - live, s.totalBytes(), s.requests, s.edits, parses, indexes, s.bytes_received,
        });
        if (s.graph_job != null) try w.writeAll("Build graph: configuring asynchronously\n") else if (s.graph_error) |err| try w.print("Build graph unavailable: {s}\n", .{@errorName(err)}) else try w.print("{s}\n", .{s.graph.summary()});
        try w.writeAll("std.zig.Ast; lazy full-file parsing; separate navigation index.\n" ++
            "Lexical navigation, completion, syntax diagnostics, symbols and formatting; no compiler semantic queries.");
    }
    pub const GraphState = enum(u32) {
        idle,
        configuring,
        ready,
        failed,
        fn printLuaClient(w: *Writer) !void {
            try luaEnum(w, "GRAPH", @This());
        }
    };
    pub fn graphState(s: *Workspace) GraphState {
        s.pollGraph();
        return if (s.graph_job != null) .configuring else if (s.graph_error != null) .failed else if (s.graph_ready) .ready else .idle;
    }
    pub fn startGraph(s: *Workspace) !void {
        s.pollGraph();
        if (s.graph_job != null) return error.GraphRefreshInProgress;
        s.graph_ready = false;
        s.graph_error = null;
        s.graph_generation +%= 1;
        s.graph_job = GraphJob.start(s.io, s.root, s.zig_exe, s.build_options) catch |err| {
            s.graph_error = err;
            return err;
        };
    }
    // Owner-thread publication: workers never touch documents, indexes, or socket buffers.
    pub fn pollGraph(s: *Workspace) void {
        const job = s.graph_job orelse return;
        if (!job.done.load(.acquire)) return;
        job.thread.?.join();
        job.thread = null;
        if (job.failure) |err| {
            s.graph_error = err;
            job.graph.deinit();
        } else {
            s.graph.deinit();
            s.graph = job.graph;
            s.graph.cancel = null;
            s.graph_ready = true;
            s.graph_error = null;
        }
        std.heap.page_allocator.destroy(job);
        s.graph_job = null;
    }
    pub fn cancelGraph(s: *Workspace) void {
        if (s.graph_job) |job| {
            job.cancel.store(true, .release);
            if (job.thread) |thread| thread.join();
            job.graph.deinit();
            std.heap.page_allocator.destroy(job);
            s.graph_job = null;
        }
    }
};

// A bounded, cancellable build-context job with isolated allocations.
// Inputs remain owned by Workspace/Cli until join; no editor API is used here.
const GraphJob = struct {
    graph: BuildGraph,
    root: []const u8,
    zig_exe: []const u8,
    options: []const []const u8,
    thread: ?std.Thread = null,
    done: std.atomic.Value(bool) = .init(false),
    cancel: std.atomic.Value(bool) = .init(false),
    failure: ?anyerror = null,
    fn start(io: Io, root: []const u8, zig_exe: []const u8, options: []const []const u8) !*GraphJob {
        const allocator = std.heap.page_allocator;
        const job = try allocator.create(GraphJob);
        errdefer allocator.destroy(job);
        job.* = .{ .graph = BuildGraph.init(allocator, io), .root = root, .zig_exe = zig_exe, .options = options };
        errdefer job.graph.deinit();
        job.graph.cancel = &job.cancel;
        job.thread = try std.Thread.spawn(.{}, run, .{job});
        return job;
    }
    fn run(job: *GraphJob) void {
        job.graph.load(job.zig_exe, job.root, job.options) catch |err| {
            job.failure = err;
        };
        job.done.store(true, .release);
    }
};

const Server = struct {
    workspace: Workspace,
    response: Writer.Allocating,
    hello: bool = false,
    stop: bool = false,
    fn init(gpa: Allocator, io: Io, root: []const u8, zig_exe: []const u8, options: []const []const u8) Server {
        return .{ .workspace = Workspace.init(gpa, io, root, zig_exe, options), .response = .init(gpa) };
    }
    fn deinit(s: *Server) void {
        s.workspace.deinit();
        s.response.deinit();
    }
    fn startResponse(s: *Server, status: Status) !*Writer {
        s.response.clearRetainingCapacity();
        const w = &s.response.writer;
        try w.writeInt(u32, @backingInt(status), .little);
        return w;
    }
    fn dispatch(s: *Server, a: Allocator, h: Header, body: []const u8) !bool {
        if (h.flags != 0) return error.BadFrame;
        const op = std.enums.fromInt(Op, h.opcode) orelse return error.UnknownOpcode;
        if (!s.hello and op != .hello) return error.HandshakeRequired;
        const notification = op == .open or op == .replace or op == .close or op == .shutdown;
        if ((op == .open or op == .replace or op == .close) and h.request_id != 0) return error.BadFrame;
        if (!notification and h.request_id == 0) return error.BadFrame;
        var r: Reader = .fixed(body);
        const engine = &s.workspace;
        engine.pollGraph();
        if (op.isQuery()) {
            const d = try engine.document(h.document_id, try r.takeInt(u32, .little));
            const offset = if (op == .definition or op == .completion) try r.takeInt(u32, .little) else 0;
            try endOfBody(&r);
            if (offset > d.source().len) return error.InvalidOffset;
            const w = try s.startResponse(.ok);
            switch (op) {
                .definition => {
                    const loc = try engine.definition(d, offset);
                    try words(w, .{ loc.revision, loc.document_id, loc.target_revision, loc.first, loc.last, loc.path.len });
                    try w.writeAll(loc.path);
                },
                .completion => {
                    const result = try engine.completion(a, d, offset);
                    var total: usize = 20;
                    var count: usize = 0;
                    for (result.items) |item| {
                        const size = 16 + item.label.len + item.detail.len + item.insert.len;
                        if (size > Info.max_body - total) break;
                        total += size;
                        count += 1;
                    }
                    try words(w, .{ result.revision, result.first, result.last, count });
                    for (result.items[0..count]) |item| {
                        try words(w, .{ item.kind, item.label.len, item.detail.len, item.insert.len });
                        try w.writeAll(item.label);
                        try w.writeAll(item.detail);
                        try w.writeAll(item.insert);
                    }
                },
                .symbols => {
                    const result = try engine.symbols(a, d);
                    try words(w, .{ d.revision, result.len });
                    for (result) |sym| {
                        try words(w, .{ sym.first, sym.last, sym.kind, sym.name.len });
                        try w.writeAll(sym.name);
                    }
                },
                .diagnostics => {
                    const result = try engine.diagnostics(a, d);
                    try words(w, .{ d.revision, result.len });
                    for (result) |diag| {
                        try words(w, .{ diag.first, diag.last, diag.severity, diag.message.len });
                        try w.writeAll(diag.message);
                    }
                },
                .format => {
                    const result = try engine.format(a, d);
                    try words(w, .{d.revision});
                    try w.writeAll(result);
                },
                else => unreachable,
            }
            return true;
        }
        switch (op) {
            .hello => {
                if (h.document_id != 0) return error.BadFrame;
                const version = try r.takeInt(u32, .little);
                try endOfBody(&r);
                if (version != Info.protocol_version) return error.ProtocolVersionMismatch;
                const w = try s.startResponse(.ok);
                try words(w, .{ Info.protocol_version, Capability.all });
                try w.writeAll("ZWE workspace engine; official AST; no compiler semantic backend");
                s.hello = true;
            },
            .open => {
                const revision = try r.takeInt(u32, .little);
                const path_len = try r.takeInt(u32, .little);
                const path = try r.take(path_len);
                const text = try r.take(r.bufferedLen());
                try engine.open(h.document_id, revision, path, text);
                return false;
            },
            .replace => {
                const base = try r.takeInt(u32, .little);
                const revision = try r.takeInt(u32, .little);
                const offset = try r.takeInt(u32, .little);
                const removed = try r.takeInt(u32, .little);
                const text = try r.take(r.bufferedLen());
                try engine.replace(h.document_id, base, revision, offset, removed, text);
                return false;
            },
            .close => {
                try endOfBody(&r);
                if (h.document_id == 0) return error.BadFrame;
                engine.close(h.document_id);
                return false;
            },
            .status => {
                try endOfBody(&r);
                try engine.writeStatus(try s.startResponse(.ok));
            },
            .refresh_graph => {
                try endOfBody(&r);
                try engine.startGraph();
                try (try s.startResponse(.ok)).writeAll("Build graph configuration started");
            },
            .graph_state => {
                try endOfBody(&r);
                const state = engine.graphState();
                const w = try s.startResponse(.ok);
                try words(w, .{ engine.graph_generation, @backingInt(state) });
                try w.writeAll(if (engine.graph_error) |err| @errorName(err) else if (state == .configuring) "Configuring build graph" else engine.graph.summary());
            },
            .shutdown => {
                try endOfBody(&r);
                s.stop = true;
                _ = try s.startResponse(.ok);
                return h.request_id != 0;
            },
            else => return error.UnknownOpcode,
        }
        return true;
    }
    fn makeError(s: *Server, h: Header, body: []const u8, err: anyerror) !u16 {
        const status = Status.fromError(err);
        const w = try s.startResponse(status);
        var opcode = h.opcode;
        if (h.request_id == 0) {
            opcode = @backingInt(if (status == .stale_revision or err == error.InvalidEdit) Op.resync_required else Op.protocol_error);
        } else if (std.enums.fromInt(Op, h.opcode)) |op| {
            if (op.isQuery()) try words(w, .{if (body.len >= 4) std.mem.readInt(u32, body[0..4], .little) else @as(u32, 0)});
        } else opcode = @backingInt(Op.protocol_error);
        try w.writeAll(switch (err) {
            error.CompilerSemanticsRequired => "Compiler type/comptime analysis is required; ZWE will not guess.",
            error.UnknownModuleContext => "Unknown module context; navigate through a known module's file imports first.",
            error.BuildGraphUnavailable => "No current build graph; request a refresh for a configured build project.",
            error.AmbiguousImport => "Different compilation contexts resolve this import differently.",
            error.StaleRevision => "Source revision mismatch; resynchronize and retry.",
            error.DefinitionNotFound => "No declaration is known at this position.",
            error.SyntaxErrors => "Formatting requires a syntactically valid file.",
            else => @errorName(err),
        });
        return opcode;
    }
    fn serveConnection(s: *Server, connection: Io.net.Stream) !void {
        var read_buffer: [16 * 1024]u8 = undefined;
        var write_buffer: [16 * 1024]u8 = undefined;
        var reader = connection.reader(s.workspace.io, &read_buffer);
        var writer = connection.writer(s.workspace.io, &write_buffer);
        var body: std.ArrayList(u8) = .empty;
        defer body.deinit(s.workspace.gpa);
        while (!s.stop) {
            const raw = reader.interface.takeArray(16) catch |err| switch (err) {
                error.EndOfStream => return,
                else => return err,
            };
            const h = Header.decode(raw);
            if (h.body_len > Info.max_body) return error.FrameTooLarge;
            try body.resize(s.workspace.gpa, h.body_len);
            try reader.interface.readSliceAll(body.items);
            s.workspace.beginRequest();
            s.workspace.bytes_received += 16 + body.items.len;
            var arena: std.heap.ArenaAllocator = .init(s.workspace.gpa);
            defer arena.deinit();
            var opcode = h.opcode;
            const reply = s.dispatch(arena.allocator(), h, body.items) catch |err| blk: {
                opcode = try s.makeError(h, body.items, err);
                break :blk true;
            };
            if (!reply) continue;
            const result = s.response.written();
            if (result.len > Info.max_body) return error.FrameTooLarge;
            const hdr: Header = .{ .body_len = @intCast(result.len), .request_id = h.request_id, .document_id = h.document_id, .opcode = opcode, .flags = 1 };
            try writer.interface.writeStruct(hdr, .little);
            try writer.interface.writeAll(result);
            try writer.interface.flush();
        }
    }
};
fn wireKind(kind: Index.Kind) u32 {
    return switch (kind) {
        .function => 1,
        .variable => 2,
        .constant => 3,
        .field, .enum_member => 4,
        .parameter, .capture => 7,
    };
}

// Compact lexical index over the official AST; not compiler semantic analysis.
pub const Index = struct {
    const none = std.math.maxInt(u32);

    pub const Kind = enum { constant, variable, function, parameter, field, enum_member, capture };
    pub const Decl = struct {
        name: []const u8,
        start: u32,
        end: u32,
        scope: u32,
        kind: Kind,
        is_pub: bool,
        symbol: u32,
        token: Token,
        visible_from: u32,
        type_node: ?Node = null,
        init_node: ?Node = null,
        next: u32 = none,
        same_name: u32 = none,
    };
    pub const ImportRef = struct {
        path: []const u8,
        members: [16][]const u8 = undefined,
        member_count: u8 = 0,
        instance_after: ?u8 = null,
    };
    pub const Resolution = union(enum) { local: u32, import: ImportRef, not_found, unsupported };
    pub const Completion = struct {
        ids: []u32,
        prefix: []const u8,
        replace_start: u32,
        import_ref: ?ImportRef = null,
        unsupported: bool = false,
        mode: enum { lexical, member, builtin, none } = .lexical,
    };
    const ScopeKind = enum { namespace, function, block, capture };
    const Scope = struct {
        start: u32,
        end: u32,
        kind: ScopeKind,
        owner: Node,
        parent: u32 = none,
        first_decl: u32 = none,
        capture_token: ?Token = null,
        is_enum: bool = false,
    };
    const Namespace = struct { scope: u32, instance: bool = false, pointer_type: bool = false };
    const Value = union(enum) { namespace: Namespace, import: ImportRef, unsupported };
    const Import = struct { path: []const u8, token: Token };

    arena: std.heap.ArenaAllocator,
    ast: *const Ast,
    decls: std.ArrayList(Decl) = .empty,
    scopes: std.ArrayList(Scope) = .empty,
    imports: std.ArrayList(Import) = .empty,
    names: std.ArrayList([]const u8) = .empty,
    symbols: std.StringHashMapUnmanaged(u32) = .empty,
    bindings: std.AutoHashMapUnmanaged(u64, u32) = .empty,
    token_symbols: []u32 = &.{},
    token_decls: []u32 = &.{},
    node_scopes: []u32 = &.{},
    node_imports: []u32 = &.{},
    expression_ends: []u32 = &.{},

    /// Borrows the document AST and its source.
    pub fn init(gpa: Allocator, ast: *const Ast) !Index {
        var self: Index = .{ .arena = .init(gpa), .ast = ast };
        errdefer self.deinit();
        self.token_symbols = try self.sentinelArray(ast.tokens.len);
        self.token_decls = try self.sentinelArray(ast.tokens.len);
        self.node_scopes = try self.sentinelArray(ast.nodes.len);
        self.node_imports = try self.sentinelArray(ast.nodes.len);
        self.expression_ends = try self.sentinelArray(ast.tokens.len);
        try self.indexNames();
        try self.indexScopes();
        try self.indexDeclarations();
        try self.indexExpressions();
        return self;
    }
    pub fn deinit(self: *Index) void {
        self.arena.deinit();
        self.* = undefined;
    }
    fn allocator(self: *Index) Allocator {
        return self.arena.allocator();
    }

    fn sentinelArray(self: *Index, len: usize) ![]u32 {
        const result = try self.allocator().alloc(u32, len);
        @memset(result, none);
        return result;
    }

    fn decoded(self: *Index, literal: []const u8) !?[]const u8 {
        return literalName(self.allocator(), literal);
    }

    fn indexNames(self: *Index) !void {
        for (0..self.ast.tokens.len) |i| {
            const token: Token = @intCast(i);
            if (self.ast.tokenTag(token) != .identifier) continue;
            const raw = self.ast.tokenSlice(token);
            const name = if (std.mem.startsWith(u8, raw, "@\"")) (try self.decoded(raw[1..]) orelse continue) else raw;
            const entry = try self.symbols.getOrPut(self.allocator(), name);
            if (!entry.found_existing) {
                entry.value_ptr.* = @intCast(self.names.items.len);
                try self.names.append(self.allocator(), name);
            }
            self.token_symbols[i] = entry.value_ptr.*;
        }
    }

    fn tokenEnd(self: *const Index, token: Token) u32 {
        return endOfToken(self.ast, token);
    }

    fn nodeEnd(self: *const Index, node: Node) u32 {
        return self.tokenEnd(self.lastToken(node));
    }

    fn closingToken(self: *const Index, first: Token) Token {
        var depth: usize = 0;
        var token = first;
        while (token < self.ast.tokens.len) : (token += 1) {
            switch (self.ast.tokenTag(token)) {
                .l_brace, .l_paren, .l_bracket => depth += 1,
                .r_brace, .r_paren, .r_bracket => {
                    if (depth <= 1) return token;
                    depth -= 1;
                },
                .eof => return token,
                else => {},
            }
        }
        return @intCast(self.ast.tokens.len - 1);
    }

    // Ast.lastToken can unwrap absent return types in recovered function prototypes.
    fn lastToken(self: *const Index, node: Node) Token {
        if (self.ast.errors.len == 0) return self.ast.lastToken(node);
        const data = self.ast.nodeData(node);
        const token = self.ast.nodeMainToken(node);
        switch (self.ast.nodeTag(node)) {
            .root => return @intCast(self.ast.tokens.len - 1),
            .identifier, .number_literal, .string_literal, .char_literal, .enum_literal, .deref => return token,
            .field_access, .unwrap_optional, .grouped_expression => return data.node_and_token[1],
            .multiline_string_literal, .error_set_decl => return data.token_and_token[1],
            .fn_decl => return self.lastToken(data.node_and_node[1]),
            .fn_proto_simple => if (data.opt_node_and_opt_node[1].unwrap()) |ret| return self.lastToken(ret),
            .fn_proto, .fn_proto_one, .fn_proto_multi => if (data.extra_and_opt_node[1].unwrap()) |ret| return self.lastToken(ret),
            else => {},
        }
        var two: [2]Node = undefined;
        const is_container = self.ast.fullContainerDecl(&two, node) != null;
        const is_delimited = self.ast.blockStatements(&two, node) != null or
            self.ast.fullStructInit(&two, node) != null or
            self.ast.builtinCallParams(&two, node) != null;
        var one: [1]Node = undefined;
        const is_call = self.ast.fullCall(&one, node) != null;
        var cursor = token;
        var previous = token;
        while (cursor < self.ast.tokens.len) : (cursor += 1) {
            switch (self.ast.tokenTag(cursor)) {
                .eof => return if (is_container or is_delimited or is_call) cursor else previous,
                .semicolon, .comma, .r_brace, .r_paren, .r_bracket, .keyword_else => return previous,
                .l_brace, .l_paren, .l_bracket => |tag| {
                    cursor = self.closingToken(cursor);
                    if ((is_container and tag == .l_brace) or is_delimited or is_call) return cursor;
                },
                else => {},
            }
            previous = cursor;
        }
        return previous;
    }

    fn captureScope(self: *Index, first: ?Token, body: Node) !void {
        const token = first orelse return;
        try self.scopes.append(self.allocator(), .{
            .start = self.ast.tokenStart(token),
            .end = self.nodeEnd(body),
            .kind = .capture,
            .owner = body,
            .capture_token = token,
        });
    }

    fn indexScopes(self: *Index) !void {
        try self.scopes.append(self.allocator(), .{
            .start = 0,
            .end = @as(u32, @intCast(self.ast.source.len)) + 1,
            .kind = .namespace,
            .owner = .root,
        });
        const functions = try self.sentinelArray(self.ast.tokens.len);
        defer self.allocator().free(functions);
        for (1..self.ast.nodes.len) |i| {
            const node: Node = @fromBackingInt(@as(u32, @intCast(i)));
            const tag = self.ast.nodeTag(node);
            var two: [2]Node = undefined;
            if (self.ast.fullContainerDecl(&two, node)) |container| {
                try self.scopes.append(self.allocator(), .{
                    .start = self.ast.tokenStart(container.ast.main_token),
                    .end = self.nodeEnd(node),
                    .kind = .namespace,
                    .owner = node,
                    .is_enum = self.ast.tokenTag(container.ast.main_token) == .keyword_enum,
                });
            } else if (self.ast.blockStatements(&two, node) != null) {
                try self.scopes.append(self.allocator(), .{
                    .start = self.ast.tokenStart(self.ast.nodeMainToken(node)),
                    .end = self.nodeEnd(node),
                    .kind = .block,
                    .owner = node,
                });
            }
            var one: [1]Node = undefined;
            if (self.ast.fullFnProto(&one, node)) |proto| {
                const tok = proto.ast.fn_token;
                if (functions[tok] == none) {
                    functions[tok] = @intCast(self.scopes.items.len);
                    try self.scopes.append(self.allocator(), .{
                        .start = self.ast.tokenStart(proto.lparen),
                        .end = self.nodeEnd(node),
                        .kind = .function,
                        .owner = node,
                    });
                } else if (tag == .fn_decl) {
                    const scope = &self.scopes.items[functions[tok]];
                    scope.end = self.nodeEnd(node);
                    scope.owner = node;
                }
            }
            if (self.ast.fullIf(node)) |branch| {
                try self.captureScope(branch.payload_token, branch.ast.then_expr);
                if (branch.ast.else_expr.unwrap()) |otherwise| try self.captureScope(branch.error_token, otherwise);
            }
            if (self.ast.fullWhile(node)) |loop| {
                try self.captureScope(loop.payload_token, loop.ast.then_expr);
                if (loop.ast.else_expr.unwrap()) |otherwise| try self.captureScope(loop.error_token, otherwise);
            }
            if (self.ast.fullFor(node)) |loop| try self.captureScope(loop.payload_token, loop.ast.then_expr);
            if (self.ast.fullSwitchCase(node)) |branch| try self.captureScope(branch.payload_token, branch.ast.target_expr);
            if (tag == .@"catch" or tag == .@"errdefer") {
                const tok = self.ast.nodeMainToken(node);
                if (tok + 2 < self.ast.tokens.len and self.ast.tokenTag(tok + 1) == .pipe) {
                    const body = if (tag == .@"catch") self.ast.nodeData(node).node_and_node[1] else self.ast.nodeData(node).node;
                    try self.captureScope(tok + 2, body);
                }
            }
        }
        std.sort.pdq(Scope, self.scopes.items, {}, struct {
            fn less(_: void, a: Scope, b: Scope) bool {
                if (a.start != b.start) return a.start < b.start;
                if (a.end != b.end) return a.end > b.end;
                return @backingInt(a.kind) < @backingInt(b.kind);
            }
        }.less);
        var stack: std.ArrayList(u32) = .empty;
        defer stack.deinit(self.allocator());
        for (self.scopes.items, 0..) |*scope, i| {
            while (stack.items.len != 0) {
                const parent = self.scopes.items[stack.items[stack.items.len - 1]];
                if (scope.start < parent.end and scope.end <= parent.end) break;
                _ = stack.pop();
            }
            scope.parent = if (stack.items.len == 0) none else stack.items[stack.items.len - 1];
            if (scope.kind != .capture) self.node_scopes[@backingInt(scope.owner)] = @intCast(i);
            try stack.append(self.allocator(), @intCast(i));
        }
    }

    fn scopeAt(self: *const Index, offset: u32) u32 {
        var lo: usize = 0;
        var hi = self.scopes.items.len;
        while (lo < hi) {
            const mid = lo + (hi - lo) / 2;
            if (self.scopes.items[mid].start <= offset) lo = mid + 1 else hi = mid;
        }
        var id: u32 = if (lo == 0) 0 else @intCast(lo - 1);
        while (id != none) {
            const scope = self.scopes.items[id];
            if (offset >= scope.start and offset < scope.end) return id;
            id = scope.parent;
        }
        return 0;
    }

    fn addDecl(self: *Index, token: Token, scope_id: u32, kind: Kind, is_pub: bool, visible_from: u32, type_node: ?Node, init_node: ?Node) !void {
        if (token >= self.token_symbols.len or self.token_decls[token] != none) return;
        const symbol = self.token_symbols[token];
        if (symbol == none or std.mem.eql(u8, self.names.items[symbol], "_")) return;
        const id: u32 = @intCast(self.decls.items.len);
        const binding = try self.bindings.getOrPut(self.allocator(), (@as(u64, scope_id) << 32) | symbol);
        try self.decls.append(self.allocator(), .{
            .name = self.names.items[symbol],
            .start = self.ast.tokenStart(token),
            .end = self.tokenEnd(token),
            .scope = scope_id,
            .kind = kind,
            .is_pub = is_pub,
            .symbol = symbol,
            .token = token,
            .visible_from = visible_from,
            .type_node = type_node,
            .init_node = init_node,
            .next = self.scopes.items[scope_id].first_decl,
            .same_name = if (binding.found_existing) binding.value_ptr.* else none,
        });
        binding.value_ptr.* = id;
        self.token_decls[token] = id;
        self.scopes.items[scope_id].first_decl = id;
    }

    fn indexDeclarations(self: *Index) !void {
        for (1..self.ast.nodes.len) |i| {
            const node: Node = @fromBackingInt(@as(u32, @intCast(i)));
            if (self.ast.fullVarDecl(node)) |variable| {
                const tok = variable.ast.mut_token + 1;
                const scope = self.scopeAt(self.ast.tokenStart(tok));
                try self.addDecl(tok, scope, if (self.ast.tokenTag(variable.ast.mut_token) == .keyword_const) .constant else .variable, variable.visib_token != null, if (self.scopes.items[scope].kind == .namespace) 0 else self.nodeEnd(node), variable.ast.type_node.unwrap(), variable.ast.init_node.unwrap());
            }
            var one: [1]Node = undefined;
            if (self.ast.fullFnProto(&one, node)) |proto| {
                if (proto.name_token) |tok| {
                    const scope = self.scopeAt(self.ast.tokenStart(tok));
                    try self.addDecl(tok, scope, .function, proto.visib_token != null, 0, null, null);
                }
            }
            if (self.ast.fullContainerField(node)) |field| {
                const tok = field.ast.main_token;
                if (self.ast.tokenTag(tok) != .identifier) continue;
                const scope = self.scopeAt(self.ast.tokenStart(tok));
                if (self.scopes.items[scope].kind != .namespace) continue;
                const is_enum = self.scopes.items[scope].is_enum;
                if (field.ast.tuple_like and !is_enum) continue;
                try self.addDecl(tok, scope, if (is_enum) .enum_member else .field, true, 0, field.ast.type_expr.unwrap(), field.ast.value_expr.unwrap());
            }
        }
        for (0..self.scopes.items.len) |i| {
            const scope = self.scopes.items[i];
            if (scope.kind == .function) {
                var one: [1]Node = undefined;
                const proto = self.ast.fullFnProto(&one, scope.owner).?;
                var it = proto.iterate(self.ast);
                while (it.next()) |param| {
                    if (param.name_token) |tok| try self.addDecl(tok, @intCast(i), .parameter, false, if (param.type_expr) |ty| self.nodeEnd(ty) else self.tokenEnd(tok), param.type_expr, null);
                }
            } else if (scope.capture_token) |first| {
                var tok = first;
                while (tok < self.ast.tokens.len and self.ast.tokenTag(tok) != .pipe) : (tok += 1) {
                    switch (self.ast.tokenTag(tok)) {
                        .identifier => try self.addDecl(tok, @intCast(i), .capture, false, self.tokenEnd(tok), null, null),
                        .asterisk, .comma => {},
                        else => break,
                    }
                }
            }
        }
    }

    fn indexExpressions(self: *Index) !void {
        for (1..self.ast.nodes.len) |i| {
            const node: Node = @fromBackingInt(@as(u32, @intCast(i)));
            const tag = self.ast.nodeTag(node);
            var two: [2]Node = undefined;
            if (self.ast.builtinCallParams(&two, node)) |params| {
                if (std.mem.eql(u8, self.ast.tokenSlice(self.ast.nodeMainToken(node)), "@import") and params.len == 1 and self.ast.nodeTag(params[0]) == .string_literal) {
                    const tok = self.ast.nodeMainToken(params[0]);
                    if (try self.decoded(self.ast.tokenSlice(tok))) |path| {
                        self.node_imports[i] = @intCast(self.imports.items.len);
                        try self.imports.append(self.allocator(), .{ .path = path, .token = tok });
                    }
                }
            }
            switch (tag) {
                .identifier,
                .field_access,
                .grouped_expression,
                .builtin_call,
                .builtin_call_comma,
                .builtin_call_two,
                .builtin_call_two_comma,
                .deref,
                .unwrap_optional,
                .call,
                .call_comma,
                .call_one,
                .call_one_comma,
                .struct_init,
                .struct_init_comma,
                .struct_init_one,
                .struct_init_one_comma,
                .struct_init_dot,
                .struct_init_dot_comma,
                .struct_init_dot_two,
                .struct_init_dot_two_comma,
                => {
                    const last = self.lastToken(node);
                    const previous = self.expression_ends[last];
                    if (previous == none or self.ast.firstToken(node) <= self.ast.firstToken(@fromBackingInt(previous))) self.expression_ends[last] = @intCast(i);
                },
                else => {},
            }
        }
    }

    fn isLexical(kind: Kind) bool {
        return kind != .field and kind != .enum_member;
    }

    fn lookup(self: *const Index, symbol: u32, start_scope: u32, offset: u32) ?u32 {
        var scope = start_scope;
        while (scope != none) : (scope = self.scopes.items[scope].parent) {
            var id = self.bindings.get((@as(u64, scope) << 32) | symbol) orelse continue;
            while (id != none) : (id = self.decls.items[id].same_name) {
                const decl = self.decls.items[id];
                if (decl.visible_from <= offset and isLexical(decl.kind)) return id;
            }
        }
        return null;
    }

    fn namespaceMember(self: *const Index, context: Namespace, name: []const u8, public_only: bool) ?u32 {
        if (context.pointer_type and !context.instance) return null;
        const symbol = self.symbols.get(name) orelse return null;
        var id = self.bindings.get((@as(u64, context.scope) << 32) | symbol) orelse return null;
        while (id != none) : (id = self.decls.items[id].same_name) {
            const decl = self.decls.items[id];
            if (public_only and !decl.is_pub) continue;
            if (context.instance) {
                if (decl.kind != .field and decl.kind != .function) continue;
            } else if (decl.kind == .field) continue;
            return id;
        }
        return null;
    }

    fn instance(value: Value) Value {
        return switch (value) {
            .namespace => |ns| .{ .namespace = .{ .scope = ns.scope, .instance = true } },
            .import => |imp| blk: {
                var result = imp;
                result.instance_after = result.member_count;
                break :blk .{ .import = result };
            },
            .unsupported => .unsupported,
        };
    }

    fn appendImport(imp: ImportRef, name: []const u8) Resolution {
        if (imp.member_count == imp.members.len) return .unsupported;
        var result = imp;
        result.members[result.member_count] = name;
        result.member_count += 1;
        return .{ .import = result };
    }

    fn memberValue(self: *const Index, value: Value, name: []const u8, public_only: bool) Resolution {
        return switch (value) {
            .namespace => |ns| if (self.namespaceMember(ns, name, public_only)) |id| .{ .local = id } else .not_found,
            .import => |imp| appendImport(imp, name),
            .unsupported => .unsupported,
        };
    }

    fn resolutionValue(self: *const Index, resolution: Resolution, depth: u8) Value {
        return switch (resolution) {
            .local => |id| self.valueOfDecl(id, depth + 1),
            .import => |imp| .{ .import = imp },
            else => .unsupported,
        };
    }

    fn valueOfDecl(self: *const Index, id: u32, depth: u8) Value {
        if (depth > 48 or id >= self.decls.items.len) return .unsupported;
        const decl = self.decls.items[id];
        if (decl.kind == .function or decl.kind == .capture or decl.kind == .enum_member) return .unsupported;
        if (decl.type_node) |ty| {
            const is_type = self.ast.nodeTag(ty) == .identifier and std.mem.eql(u8, self.ast.tokenSlice(self.ast.nodeMainToken(ty)), "type");
            if (!is_type) return instance(self.valueOfExpr(ty, depth + 1));
        }
        if (decl.init_node) |node| return self.valueOfExpr(node, depth + 1);
        return .unsupported;
    }

    fn valueOfExpr(self: *const Index, node: Node, depth: u8) Value {
        if (depth > 48) return .unsupported;
        if (self.node_imports[@backingInt(node)] != none) return .{ .import = .{ .path = self.imports.items[self.node_imports[@backingInt(node)]].path } };
        const main_token = self.ast.nodeMainToken(node);
        const offset = self.ast.tokenStart(main_token);
        const data = self.ast.nodeData(node);
        switch (self.ast.nodeTag(node)) {
            .identifier => {
                const symbol = self.token_symbols[main_token];
                if (symbol == none) return .unsupported;
                const id = self.lookup(symbol, self.scopeAt(offset), offset) orelse return .unsupported;
                return self.valueOfDecl(id, depth + 1);
            },
            .field_access => return self.resolutionValue(self.memberValue(self.valueOfExpr(data.node_and_token[0], depth + 1), self.nameAt(data.node_and_token[1]) orelse return .unsupported, false), depth + 1),
            .grouped_expression => return self.valueOfExpr(data.node_and_token[0], depth + 1),
            .deref => return self.valueOfExpr(data.node, depth + 1),
            .ptr_type, .ptr_type_aligned, .ptr_type_sentinel, .ptr_type_bit_range => {
                const pointer = self.ast.fullPtrType(node).?;
                if (pointer.size != .one) return .unsupported;
                var value = self.valueOfExpr(pointer.ast.child_type, depth + 1);
                if (value == .namespace) {
                    if (value.namespace.pointer_type) return .unsupported;
                    value.namespace.pointer_type = true;
                }
                return value;
            },
            .builtin_call, .builtin_call_comma, .builtin_call_two, .builtin_call_two_comma => {
                var two: [2]Node = undefined;
                const params = self.ast.builtinCallParams(&two, node).?;
                if (params.len == 0 and std.mem.eql(u8, self.ast.tokenSlice(main_token), "@This")) {
                    var scope = self.scopeAt(offset);
                    while (scope != none) : (scope = self.scopes.items[scope].parent) {
                        if (self.scopes.items[scope].kind == .namespace) return .{ .namespace = .{ .scope = scope } };
                    }
                }
                return .unsupported;
            },
            else => {
                var two: [2]Node = undefined;
                if (self.ast.fullContainerDecl(&two, node) != null) return .{ .namespace = .{ .scope = self.node_scopes[@backingInt(node)] } };
                if (self.ast.fullStructInit(&two, node)) |initializer| {
                    if (initializer.ast.type_expr.unwrap()) |ty| return instance(self.valueOfExpr(ty, depth + 1));
                }
                return .unsupported;
            },
        }
    }

    fn nameAt(self: *const Index, token: Token) ?[]const u8 {
        const symbol = self.token_symbols[token];
        return if (symbol == none) null else self.names.items[symbol];
    }

    fn tokenBeforeOrAt(self: *const Index, offset: u32) ?Token {
        var lo: usize = 0;
        var hi = self.ast.tokens.len;
        while (lo < hi) {
            const mid = lo + (hi - lo) / 2;
            if (self.ast.tokens.items(.start)[mid] <= offset) lo = mid + 1 else hi = mid;
        }
        return if (lo == 0) null else @intCast(lo - 1);
    }

    fn receiverEndingAt(self: *const Index, token: Token, depth: u8) Value {
        if (depth > 48) return .unsupported;
        const node = self.expression_ends[token];
        if (node != none) return self.valueOfExpr(@fromBackingInt(node), depth + 1);
        if (self.ast.tokenTag(token) != .identifier) return .unsupported;
        if (token >= 2 and self.ast.tokenTag(token - 1) == .period) return self.resolutionValue(self.memberValue(self.receiverEndingAt(token - 2, depth + 1), self.nameAt(token) orelse return .unsupported, false), depth + 1);
        const symbol = self.token_symbols[token];
        const offset = self.ast.tokenStart(token);
        const id = self.lookup(symbol, self.scopeAt(offset), offset) orelse return .unsupported;
        return self.valueOfDecl(id, depth + 1);
    }

    pub fn definition(self: *const Index, offset: u32) Resolution {
        if (offset > self.ast.source.len) return .not_found;
        const tok = self.tokenBeforeOrAt(offset) orelse return .not_found;
        if (offset >= self.tokenEnd(tok)) return .not_found;
        if (self.token_decls[tok] != none) return .{ .local = self.token_decls[tok] };
        if (self.ast.tokenTag(tok) == .string_literal) {
            for (self.imports.items) |imp| if (imp.token == tok) return .{ .import = .{ .path = imp.path } };
            return .not_found;
        }
        if (self.ast.tokenTag(tok) != .identifier) return .not_found;
        if (tok > 0 and self.ast.tokenTag(tok - 1) == .period) {
            if (tok < 2) return .unsupported;
            return self.memberValue(self.receiverEndingAt(tok - 2, 0), self.nameAt(tok) orelse return .unsupported, false);
        }
        const symbol = self.token_symbols[tok];
        const id = self.lookup(symbol, self.scopeAt(offset), offset) orelse return .not_found;
        return .{ .local = id };
    }

    pub fn exported(self: *const Index, name: []const u8) Resolution {
        return self.memberValue(.{ .namespace = .{ .scope = 0 } }, name, true);
    }

    pub fn member(self: *const Index, id: u32, name: []const u8) Resolution {
        return self.memberValue(self.valueOfDecl(id, 0), name, true);
    }

    pub fn memberAsInstance(self: *const Index, id: u32, name: []const u8) Resolution {
        return self.memberValue(instance(self.valueOfDecl(id, 0)), name, true);
    }

    fn appendMembers(self: *const Index, gpa: Allocator, out: *std.ArrayList(u32), context: Namespace, prefix: []const u8, limit: usize, public_only: bool) !void {
        if (context.pointer_type and !context.instance) return;
        var id = self.scopes.items[context.scope].first_decl;
        while (id != none and out.items.len < limit) : (id = self.decls.items[id].next) {
            const decl = self.decls.items[id];
            if (public_only and !decl.is_pub) continue;
            if (!std.mem.startsWith(u8, decl.name, prefix)) continue;
            if (context.instance) {
                if (decl.kind != .field and decl.kind != .function) continue;
            } else if (decl.kind == .field) continue;
            try out.append(gpa, id);
        }
    }

    pub fn members(self: *const Index, gpa: Allocator, id: ?u32, as_instance: bool, prefix: []const u8, limit: usize) ![]u32 {
        var result: std.ArrayList(u32) = .empty;
        errdefer result.deinit(gpa);
        var value: Value = if (id) |decl| self.valueOfDecl(decl, 0) else .{ .namespace = .{ .scope = 0 } };
        if (as_instance) value = instance(value);
        if (value == .namespace) try self.appendMembers(gpa, &result, value.namespace, prefix, limit, true);
        return result.toOwnedSlice(gpa);
    }

    pub fn completionTarget(self: *const Index, id: u32, as_instance: bool) Resolution {
        var value = self.valueOfDecl(id, 0);
        if (as_instance) value = instance(value);
        return switch (value) {
            .namespace => .{ .local = id },
            .import => |imp| .{ .import = imp },
            .unsupported => .unsupported,
        };
    }

    pub fn complete(self: *const Index, gpa: Allocator, offset: u32, limit: usize) !Completion {
        var out: std.ArrayList(u32) = .empty;
        errdefer out.deinit(gpa);
        var prefix: []const u8 = "";
        var replace_start = @min(offset, @as(u32, @intCast(self.ast.source.len)));
        var before = self.tokenBeforeOrAt(replace_start);
        if (before) |tok| {
            if (self.ast.tokenStart(tok) == replace_start and self.ast.tokenTag(tok) != .identifier) before = if (tok > 0) tok - 1 else null;
        }
        if (before) |tok| {
            const end = self.tokenEnd(tok);
            const tag = self.ast.tokenTag(tok);
            const line_start = if (std.mem.lastIndexOfScalar(u8, self.ast.source[0..replace_start], '\n')) |nl| nl + 1 else 0;
            if (((tag == .doc_comment or tag == .container_doc_comment) and replace_start <= end) or
                (end <= replace_start and std.mem.find(u8, self.ast.source[@max(end, line_start)..replace_start], "//") != null))
                return .{ .ids = try out.toOwnedSlice(gpa), .prefix = "", .replace_start = offset, .mode = .none };
        } else if (std.mem.find(u8, self.ast.source[0..replace_start], "//") != null) {
            const line_start = if (std.mem.lastIndexOfScalar(u8, self.ast.source[0..replace_start], '\n')) |nl| nl + 1 else 0;
            if (std.mem.find(u8, self.ast.source[line_start..replace_start], "//") != null)
                return .{ .ids = try out.toOwnedSlice(gpa), .prefix = "", .replace_start = offset, .mode = .none };
        }
        if (before) |tok| {
            const start = self.ast.tokenStart(tok);
            const tag = self.ast.tokenTag(tok);
            if ((tag == .builtin or tag == .invalid) and start < replace_start and self.ast.source[start] == '@') {
                const candidate = self.ast.source[start..replace_start];
                for (candidate[1..]) |c| {
                    if (!std.ascii.isAlphanumeric(c) and c != '_') break;
                } else return .{ .ids = try out.toOwnedSlice(gpa), .prefix = candidate, .replace_start = start, .mode = .builtin };
            }
            const keyword = if (tag.lexeme()) |raw| std.zig.Token.getKeyword(raw) != null else false;
            if ((tag == .identifier or keyword) and replace_start <= self.tokenEnd(tok)) {
                prefix = self.ast.source[start..replace_start];
                replace_start = start;
                if (std.mem.startsWith(u8, prefix, "@\"")) {
                    prefix = prefix[2..];
                    replace_start += 2;
                    if (std.mem.findScalar(u8, prefix, '\\') != null) return .{ .ids = try out.toOwnedSlice(gpa), .prefix = prefix, .replace_start = replace_start, .unsupported = true };
                }
                before = if (tok == 0) null else tok - 1;
            } else if ((self.ast.tokenTag(tok) == .string_literal or self.ast.tokenTag(tok) == .multiline_string_literal_line or self.ast.tokenTag(tok) == .char_literal) and offset < self.tokenEnd(tok)) {
                return .{ .ids = try out.toOwnedSlice(gpa), .prefix = "", .replace_start = offset, .mode = .none };
            }
        }
        if (before) |dot| {
            if (self.ast.tokenTag(dot) == .period) {
                const value = if (dot == 0) Value.unsupported else self.receiverEndingAt(dot - 1, 0);
                var result: Completion = .{ .ids = undefined, .prefix = prefix, .replace_start = replace_start, .mode = .member };
                switch (value) {
                    .namespace => |ns| try self.appendMembers(gpa, &out, ns, prefix, limit, false),
                    .import => |imp| result.import_ref = imp,
                    .unsupported => result.unsupported = true,
                }
                result.ids = try out.toOwnedSlice(gpa);
                return result;
            }
        }
        var seen: std.AutoHashMapUnmanaged(u32, void) = .empty;
        defer seen.deinit(gpa);
        var scope = self.scopeAt(offset);
        while (scope != none and out.items.len < limit) : (scope = self.scopes.items[scope].parent) {
            var id = self.scopes.items[scope].first_decl;
            while (id != none and out.items.len < limit) : (id = self.decls.items[id].next) {
                const decl = self.decls.items[id];
                if (!isLexical(decl.kind) or decl.visible_from > offset or !std.mem.startsWith(u8, decl.name, prefix)) continue;
                if ((try seen.getOrPut(gpa, decl.symbol)).found_existing) continue;
                try out.append(gpa, id);
            }
        }
        return .{ .ids = try out.toOwnedSlice(gpa), .prefix = prefix, .replace_start = replace_start };
    }
};

// Version-pinned BSP adapter. Configuration owns its data in this arena.
// Compiler context is retained: the same file can resolve differently per build step.
pub const BuildGraph = struct {
    const Configuration = std.Build.Configuration;
    const Message = std.zig.Server.Message;
    const linux = std.os.linux;
    const Module = struct {
        compilation_root: usize,
        root: ?[]const u8,
        generated: bool,
        imports: std.StringHashMapUnmanaged(usize) = .empty,
    };
    const Env = struct {
        zig_exe: []const u8,
        lib_dir: []const u8,
        std_dir: []const u8,
        global_cache_dir: []const u8,
        version: []const u8,
        env: struct { ZIG_LOCAL_CACHE_DIR: ?[]const u8 = null },
    };
    cancel: ?*const std.atomic.Value(bool) = null,
    gpa: Allocator,
    io: Io,
    arena: std.heap.ArenaAllocator,
    project_root: []const u8 = "",
    compiler: ?Env = null,
    std_root: ?[]const u8 = null,
    modules: std.ArrayList(Module) = .empty,
    module_ids: std.AutoHashMapUnmanaged(u64, usize) = .empty,
    files: std.StringHashMapUnmanaged(std.ArrayList(usize)) = .empty,
    edge_count: usize = 0,
    description: []const u8 = "BSP has not been configured",

    fn init(gpa: Allocator, io: Io) BuildGraph {
        return .{ .gpa = gpa, .io = io, .arena = .init(gpa) };
    }
    fn deinit(g: *BuildGraph) void {
        g.arena.deinit();
    }
    fn summary(g: *const BuildGraph) []const u8 {
        return g.description;
    }
    fn refreshWithOptions(g: *BuildGraph, zig_exe: []const u8, root: []const u8, options: []const []const u8) !void {
        var next = init(g.gpa, g.io);
        next.cancel = g.cancel;
        errdefer next.deinit();
        try next.load(zig_exe, root, options);
        g.deinit();
        g.* = next;
    }
    fn load(g: *BuildGraph, zig_exe: []const u8, root: []const u8, options: []const []const u8) !void {
        const a = g.arena.allocator();
        g.project_root = try Io.Dir.cwd().realPathFileAlloc(g.io, root, a);
        // One deadline covers both environment discovery and build configuration.
        const deadline = (try nowMs()) + Info.graph_timeout_ms;
        const env_bytes = try g.capture(&.{ zig_exe, "env" }, deadline);
        var diagnostics: std.zon.parse.Diagnostics = undefined;
        const env = try std.zon.parse.fromSlice(Env, .{
            .gpa = g.gpa,
            .arena = a,
            .source = try a.dupeSentinel(u8, env_bytes, 0),
            .diagnostics = &diagnostics,
            .ignore_unknown_fields = true,
        });
        if (!std.mem.eql(u8, env.version, Info.zig_version)) return error.UnsupportedZigVersion;
        g.compiler = env;
        g.std_root = try g.path(&.{ env.std_dir, "std.zig" });
        var argv: std.ArrayList([]const u8) = .empty;
        try argv.appendSlice(a, &.{ env.zig_exe, "build", "--listen=-" });
        for (options) |option| {
            if (option.len == 0 or option[0] == '-') return error.InvalidBuildOption;
            try argv.append(a, try std.fmt.allocPrint(a, "-D{s}", .{option}));
        }
        var child = try std.process.spawn(g.io, .{
            .argv = argv.items,
            .cwd = .{ .path = g.project_root },
            .stdin = .pipe,
            .stdout = .pipe,
            .stderr = .inherit,
        });
        defer child.kill(g.io);
        var body: std.ArrayList(u8) = .empty;
        defer body.deinit(g.gpa);
        var handshaken = false;
        while (true) {
            var raw_header: [@sizeOf(Message.Header)]u8 = undefined;
            try readExact(child.stdout.?.handle, &raw_header, deadline, g.cancel);
            var r: Reader = .fixed(&raw_header);
            const header = try r.takeStruct(Message.Header, .little);
            // Unlike receiveMessageWithMultiReader, reject oversized bodies before buffering them.
            if (header.bytes_len > 16 * 1024 * 1024) return error.BspMessageTooLarge;
            try body.resize(g.gpa, header.bytes_len);
            try readExact(child.stdout.?.handle, body.items, deadline, g.cancel);
            if (!handshaken) {
                if (header.tag != .bsp_handshake) return error.InvalidBspHandshake;
                var payload: Reader = .fixed(body.items);
                const hello = try payload.takeStruct(Message.Handshake, .little);
                if (hello.version != std.zig.Server.build_system_version) return error.UnsupportedBspVersion;
                handshaken = true;
                continue;
            }
            switch (header.tag) {
                .bsp_configuration_failed => {
                    var bundle = try std.zig.Server.allocErrorBundle(g.gpa, body.items);
                    defer bundle.deinit(g.gpa);
                    // The Neovim client includes captured stderr in a failed-refresh notification.
                    bundle.renderToStderr(g.io, .{}, .off) catch {};
                    return error.ConfigurationFailed;
                },
                .bsp_configuration => {},
                else => continue,
            }
            if (body.items.len == 0 or std.mem.findScalar(u8, body.items, 0) != null) return error.InvalidConfigurationPath;
            const config_path = try g.path(&.{ g.project_root, body.items });
            const file = try Io.Dir.cwd().openFile(g.io, config_path, .{});
            defer file.close(g.io);
            const config = try Configuration.loadFile(a, g.io, file);
            var compilations: usize = 0;
            for (config.steps, 0..) |step, i| {
                const data = step.extended.get(config.extra);
                if (data != .compile) continue;
                compilations += 1;
                _ = try g.addModule(&config, @intCast(i), data.compile.root_module, g.modules.items.len);
            }
            var unavailable: usize = 0;
            for (g.modules.items) |m| unavailable += @intFromBool(m.root == null);
            g.description = try std.fmt.allocPrint(a, "BSP v{d}: {d} compilation contexts, {d} module contexts, {d} import edges; {d} unavailable roots; configured only", .{ std.zig.Server.build_system_version, compilations, g.modules.items.len, g.edge_count, unavailable });
            return;
        }
    }
    fn addModule(g: *BuildGraph, config: *const Configuration, step: u32, index: Configuration.Module.Index, root_id: usize) anyerror!usize {
        const key = (@as(u64, step) << 32) | @as(u64, @backingInt(index));
        if (g.module_ids.get(key)) |id| return id;
        const a = g.arena.allocator();
        const m = index.get(config);
        const source = if (m.root_source_file.unwrap()) |p| p.get(config) else null;
        const root = if (source) |p| try g.lazyPath(config, p) else null;
        const id = g.modules.items.len;
        try g.modules.append(a, .{ .compilation_root = root_id, .root = root, .generated = if (source) |p| p == .generated else false });
        try g.module_ids.put(a, key, id); // Publish before recursion to handle cyclic module graphs.
        if (root) |p| try g.addFile(p, id);
        const imports = m.import_table.get(config).imports.mal;
        for (imports.items(.name), imports.items(.module)) |name, imported| {
            const child = try g.addModule(config, step, imported, root_id);
            try g.modules.items[id].imports.put(a, name.slice(config), child);
            g.edge_count += 1;
        }
        return id;
    }
    fn lazyPath(g: *BuildGraph, config: *const Configuration, p: Configuration.LazyPath) !?[]const u8 {
        const env = g.compiler.?;
        return switch (p) {
            .source_path => |v| try g.path(&.{ g.project_root, if (v.owner.get(config)) |pkg| pkg.root_path.slice(config) else "", v.sub_path.slice(config) }),
            .generated => null, // No build step is requested, so no generated-file event exists.
            .relative => |v| switch (v.flags.base) {
                .cwd, .build_root => try g.path(&.{ g.project_root, v.sub_path.slice(config) }),
                .zig_lib => try g.path(&.{ env.lib_dir, v.sub_path.slice(config) }),
                .zig_exe => try g.path(&.{env.zig_exe}),
                .global_cache => try g.path(&.{ env.global_cache_dir, v.sub_path.slice(config) }),
                .local_cache => try g.path(&.{ g.project_root, env.env.ZIG_LOCAL_CACHE_DIR orelse ".zig-cache", v.sub_path.slice(config) }),
                else => null,
            },
        };
    }
    fn path(g: *BuildGraph, pieces: []const []const u8) ![]const u8 {
        return g.normalizePath(g.arena.allocator(), pieces);
    }
    fn normalizePath(g: *BuildGraph, a: Allocator, pieces: []const []const u8) ![]const u8 {
        const absolute = try Path.resolve(a, pieces);
        return Io.Dir.cwd().realPathFileAlloc(g.io, absolute, a) catch absolute;
    }
    fn addFile(g: *BuildGraph, path_value: []const u8, module: usize) !void {
        const a = g.arena.allocator();
        if (g.files.getPtr(path_value)) |list| {
            for (list.items) |id| if (id == module) return;
            try list.append(a, module);
        } else {
            var list: std.ArrayList(usize) = .empty;
            try list.append(a, module);
            try g.files.put(a, try a.dupe(u8, path_value), list);
        }
    }
    fn noteFileImport(g: *BuildGraph, importer: []const u8, imported: []const u8) !void {
        var temp: std.heap.ArenaAllocator = .init(g.gpa);
        defer temp.deinit();
        const from = try g.normalizePath(temp.allocator(), &.{ g.project_root, importer });
        const to = try g.normalizePath(temp.allocator(), &.{ g.project_root, imported });
        if (std.mem.eql(u8, from, to)) return;
        const contexts = g.files.get(from) orelse return;
        for (contexts.items) |id| try g.addFile(to, id);
    }
    fn resolveImport(g: *BuildGraph, from_path: []const u8, name: []const u8) !?[]const u8 {
        var temp: std.heap.ArenaAllocator = .init(g.gpa);
        defer temp.deinit();
        const from = try g.normalizePath(temp.allocator(), &.{ g.project_root, from_path });
        const contexts = g.files.get(from) orelse return error.UnknownModuleContext;
        var result: ?[]const u8 = null;
        var absent = false;
        for (contexts.items) |id| {
            const m = g.modules.items[id];
            const target_id: ?usize = m.imports.get(name) orelse if (std.mem.eql(u8, name, "root")) m.compilation_root else null;
            const target: ?[]const u8 = if (target_id) |to|
                g.modules.items[to].root orelse return if (g.modules.items[to].generated) error.GeneratedModuleUnavailable else error.ModuleRootUnavailable
            else if (std.mem.eql(u8, name, "std")) g.std_root else if (std.mem.eql(u8, name, "builtin")) return error.GeneratedModuleUnavailable else null;
            if (target) |p| {
                if (result) |old| {
                    if (!std.mem.eql(u8, old, p)) return error.AmbiguousImport;
                }
                result = p;
            } else absent = true;
        }
        if (result != null and absent) return error.AmbiguousImport;
        return result;
    }
    fn capture(g: *BuildGraph, argv: []const []const u8, deadline: u64) ![]const u8 {
        var child = try std.process.spawn(g.io, .{
            .argv = argv,
            .cwd = .{ .path = g.project_root },
            .stdin = .ignore,
            .stdout = .pipe,
            .stderr = .inherit,
        });
        defer child.kill(g.io);
        var output: std.ArrayList(u8) = .empty;
        var buffer: [4096]u8 = undefined;
        while (true) {
            const n = try readSome(child.stdout.?.handle, &buffer, deadline, g.cancel);
            if (n == 0) return output.items;
            if (output.items.len + n > 1024 * 1024) return error.BspMessageTooLarge;
            try output.appendSlice(g.arena.allocator(), buffer[0..n]);
        }
    }
    // Small Linux deadline adapter retained deliberately: cap allocation before reads,
    // preserve one absolute deadline, including across partial reads.
    fn nowMs() !u64 {
        var ts: linux.timespec = undefined;
        if (linux.errno(linux.clock_gettime(.MONOTONIC, &ts)) != .SUCCESS) return error.BspClockFailed;
        return @as(u64, @intCast(ts.sec)) * 1000 + @as(u64, @intCast(ts.nsec)) / 1_000_000;
    }
    fn readSome(fd: linux.fd_t, bytes: []u8, deadline: u64, cancel: ?*const std.atomic.Value(bool)) !usize {
        while (true) {
            if (cancel) |flag| if (flag.load(.acquire)) return error.Canceled;
            const now = try nowMs();
            if (now >= deadline) return error.BspTimeout;
            var fds = [_]linux.pollfd{.{ .fd = fd, .events = linux.POLL.IN, .revents = 0 }};
            const ready = linux.poll(&fds, 1, @intCast(@min(deadline - now, 50)));
            switch (linux.errno(ready)) {
                .SUCCESS => if (ready == 0) continue,
                .INTR => continue,
                else => return error.BspReadFailed,
            }
            const n = linux.read(fd, bytes.ptr, bytes.len);
            switch (linux.errno(n)) {
                .SUCCESS => return n,
                .INTR, .AGAIN => continue,
                else => return error.BspReadFailed,
            }
        }
    }
    fn readExact(fd: linux.fd_t, bytes: []u8, deadline: u64, cancel: ?*const std.atomic.Value(bool)) !void {
        var n: usize = 0;
        while (n < bytes.len) {
            const count = try readSome(fd, bytes[n..], deadline, cancel);
            if (count == 0) return error.BspEndOfStream;
            n += count;
        }
    }
};

// Read-only ZON metadata. JSON is used only by this one-shot CLI, not the editor wire protocol.
pub const Manifest = struct {
    const Zoir = std.zig.Zoir;
    const ZonNode = Zoir.Node;

    pub const Project = struct {
        manifest: []const u8,
        dependencies: std.json.Value = .{ .object = .empty },
        minimum_zig_version: ?[]const u8 = null,
    };
    pub const Failure = struct { manifest: []const u8, @"error": []const u8 };

    pub fn run(init: std.process.Init, args: []const []const u8) !void {
        const arena = init.arena.allocator();
        const paths = if (args.len != 0) args else blk: {
            var input = Io.File.stdin().readerStreaming(init.io, &.{});
            const json = try input.interface.allocRemaining(arena, .limited(16 * 1024 * 1024));
            break :blk try std.json.parseFromSliceLeaky([]const []const u8, arena, json, .{});
        };
        if (paths.len > 4096) return error.TooManyManifests;
        var projects: std.ArrayList(Project) = .empty;
        var errors: std.ArrayList(Failure) = .empty;
        for (paths) |path| {
            var detail: ?[]const u8 = null;
            const project = load(init.gpa, init.io, arena, path, &detail) catch |err| {
                if (err == error.OutOfMemory) return err;
                try errors.append(arena, .{ .manifest = path, .@"error" = detail orelse @errorName(err) });
                continue;
            };
            try projects.append(arena, project);
        }
        var buffer: [8192]u8 = undefined;
        var output = std.Io.File.stdout().writerStreaming(init.io, &buffer);
        try std.json.Stringify.value(.{ .projects = projects.items, .errors = errors.items }, .{
            .emit_null_optional_fields = false,
        }, &output.interface);
        try output.interface.writeByte('\n');
        try output.interface.flush();
    }

    pub fn load(gpa: Allocator, io: Io, arena: Allocator, path: []const u8, detail: *?[]const u8) !Project {
        if (!Path.isAbsolute(path) or std.mem.findScalar(u8, path, 0) != null) return error.ExpectedAbsoluteManifestPath;
        var scratch: std.heap.ArenaAllocator = .init(gpa);
        defer scratch.deinit();
        const temp = scratch.allocator();
        const source = try std.Io.Dir.cwd().readFileAllocOptions(
            io,
            path,
            temp,
            .limited(4 * 1024 * 1024),
            .of(u8),
            0,
        );
        return parse(temp, arena, source, path, detail);
    }

    // Source-independent metadata is allocated in the caller's request arena.
    pub fn parse(temp: Allocator, arena: Allocator, source: [:0]const u8, path: []const u8, detail: *?[]const u8) !Project {
        if (source.len > 4 * 1024 * 1024) return error.FileTooLarge;
        var tree = try std.zig.Ast.parse(temp, source, .{ .mode = .zon });
        defer tree.deinit(temp);
        const zoir = try std.zig.ZonGen.generate(temp, tree, .{});
        defer zoir.deinit(temp);
        if (zoir.hasCompileErrors()) {
            const problem = zoir.compile_errors[0];
            const token = problem.token.unwrap() orelse tree.nodeMainToken(
                @fromBackingInt(@intCast(problem.node_or_offset)),
            );
            const loc = tree.tokenLocation(0, token);
            const offset = if (problem.token != .none) problem.node_or_offset else 0;
            detail.* = try std.fmt.allocPrint(arena, "{d}:{d}: {s}", .{
                loc.line + 1, loc.column + offset + 1, problem.msg.get(&zoir),
            });
            return error.InvalidZon;
        }

        var project: Project = .{ .manifest = try arena.dupe(u8, path) };
        const root = try fields(ZonNode.Index.root.get(&zoir));
        for (root.names, 0..) |name, i| {
            const value = root.vals.at(@intCast(i)).get(&zoir);
            if (std.mem.eql(u8, name.get(&zoir), "minimum_zig_version")) {
                project.minimum_zig_version = try string(arena, value);
            } else if (std.mem.eql(u8, name.get(&zoir), "dependencies")) {
                const dependencies = try fields(value);
                for (dependencies.names, 0..) |dep_name, j| {
                    const dependency = try dependencyValue(arena, &zoir, dependencies.vals.at(@intCast(j)));
                    try project.dependencies.object.put(arena, try arena.dupe(u8, dep_name.get(&zoir)), dependency);
                }
            }
        }
        return project;
    }

    fn fields(node: ZonNode) !@FieldType(ZonNode, "struct_literal") {
        return switch (node) {
            .struct_literal => |value| value,
            .empty_literal => .{ .names = &.{}, .vals = .{ .start = .root, .len = 0 } },
            else => error.ExpectedObject,
        };
    }

    fn string(arena: Allocator, node: ZonNode) ![]const u8 {
        return switch (node) {
            .string_literal => |value| try arena.dupe(u8, value),
            else => error.ExpectedString,
        };
    }

    fn dependencyValue(arena: Allocator, zoir: *const Zoir, node: ZonNode.Index) !std.json.Value {
        const object = try fields(node.get(zoir));
        var result: std.json.Value = .{ .object = .empty };
        for (object.names, 0..) |name, i| {
            const key = name.get(zoir);
            const value = object.vals.at(@intCast(i)).get(zoir);
            if (std.mem.eql(u8, key, "url") or std.mem.eql(u8, key, "path") or std.mem.eql(u8, key, "hash")) {
                try result.object.put(arena, try arena.dupe(u8, key), .{ .string = try string(arena, value) });
            } else if (std.mem.eql(u8, key, "lazy")) {
                const lazy = switch (value) {
                    .true => true,
                    .false => false,
                    else => return error.ExpectedBoolean,
                };
                try result.object.put(arena, "lazy", .{ .bool = lazy });
            }
        }
        if (result.object.contains("url") == result.object.contains("path"))
            return error.DependencyMustHaveExactlyOneUrlOrPath;
        return result;
    }
};

pub const Cli = struct {
    const Command = enum { @"--help", @"--version", @"--print-lua", serve, manifests };
    const Option = enum { @"--socket", @"--root", @"--zig", @"--build-option" };
    pub fn run(init: std.process.Init) !void {
        if (builtin.os.tag != .linux) @compileError("ZWE currently targets Linux.");
        if (comptime !std.mem.eql(u8, builtin.zig_version_string, Info.zig_version))
            @compileError("Build with Zig " ++ Info.zig_version ++ "; compiler-facing APIs are version-pinned.");
        const args = try init.minimal.args.toSlice(init.arena.allocator());
        const command = if (args.len == 1) Command.@"--help" else std.meta.stringToEnum(Command, args[1]) orelse return error.InvalidArguments;
        if (command == .serve) return serve(init, args[2..]);
        if (command == .manifests) return Manifest.run(init, args[2..]);
        if (args.len > 2) return error.InvalidArguments;
        var buffer: [4096]u8 = undefined;
        var stdout = Io.File.stdout().writer(init.io, &buffer);
        const w = &stdout.interface;
        switch (command) {
            .@"--version" => try Info.printVersion(w),
            .@"--print-lua" => try LuaClient.print(w),
            .@"--help" => {
                try Info.printVersion(w);
                try w.writeAll(
                    \\zwe --help | --version | --print-lua
                    \\zwe manifests [ABS_MANIFEST ...]  (or JSON array on stdin)
                    \\zwe serve --socket ABS_PATH --root ABS_ROOT --zig ZIG [--build-option NAME=VALUE]...
                    \\
                    \\Build: zig build-exe assets/zwe.zig -O safe -femit-bin=zwe
                    \\Tests: zig test assets/zwe.zig
                    \\Client: zwe --print-lua > ~/.config/nvim/lua/zwe.lua
                    \\Setup: require('zwe').setup({cmd='zwe', zig='zig'})
                    \\
                    \\Neovim commands: ZweDefinition, ZweComplete, ZweSymbols, ZweFormat,
                    \\ZweStatus, ZweRefresh, ZweRestart[!], ZweStop[!].
                    \\Set build_graph=false for syntax-only operation. Graph configuration executes build.zig.
                    \\Build refresh runs in an isolated worker; query graph_state for publication. Pipe reads are bounded.
                    \\Uses official AST parsing/formatting; navigation is lexical, not full compiler semantics.
                    \\
                );
            },
            .serve, .manifests => unreachable,
        }
        try w.flush();
    }
    fn serve(init: std.process.Init, args: []const []const u8) !void {
        const gpa = init.gpa;
        const io = init.io;
        var socket: ?[]const u8 = null;
        var root: ?[]const u8 = null;
        var zig: []const u8 = "zig";
        var options: std.ArrayList([]const u8) = .empty;
        defer options.deinit(gpa);
        var i: usize = 0;
        while (i < args.len) : (i += 2) {
            if (i + 1 == args.len) return error.MissingArgumentValue;
            const option = std.meta.stringToEnum(Option, args[i]) orelse return error.InvalidArguments;
            switch (option) {
                .@"--socket" => socket = args[i + 1],
                .@"--root" => root = args[i + 1],
                .@"--zig" => zig = args[i + 1],
                .@"--build-option" => try options.append(gpa, args[i + 1]),
            }
        }
        const socket_path = socket orelse return error.MissingSocketPath;
        const project_root = root orelse return error.MissingProjectRoot;
        if (!Path.isAbsolute(socket_path) or !Path.isAbsolute(project_root)) return error.ExpectedAbsolutePath;
        if (std.mem.findScalar(u8, socket_path, 0) != null or socket_path.len >= 108) return error.InvalidSocketPath;
        const real_root = try Io.Dir.realPathFileAbsoluteAlloc(io, project_root, gpa);
        defer gpa.free(real_root);
        const address = try Io.net.UnixAddress.init(socket_path);
        var listener = try address.listen(io, .{ .kernel_backlog = 1 });
        defer listener.deinit(io);
        defer Io.Dir.deleteFileAbsolute(io, socket_path) catch {};
        const socket_z = try gpa.dupeSentinel(u8, socket_path, 0);
        defer gpa.free(socket_z);
        if (std.os.linux.errno(std.os.linux.chmod(socket_z, 0o600)) != .SUCCESS) return error.SocketPermissionsFailed;
        var server = Server.init(gpa, io, real_root, zig, options.items);
        defer server.deinit();
        const connection = try listener.accept(io);
        defer connection.close(io);
        try server.serveConnection(connection);
    }
};
pub fn main(init: std.process.Init) !void {
    try Cli.run(init);
}

