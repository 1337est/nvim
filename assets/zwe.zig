fn indexTestOffset(source: []const u8, needle: []const u8, delta: usize) u32 {
    return @intCast((std.mem.find(u8, source, needle) orelse @panic("missing fixture marker")) + delta);
}

fn indexTestLocal(index: *const Index, source: []const u8, needle: []const u8, delta: usize, name: []const u8) !u32 {
    const resolution = index.definition(indexTestOffset(source, needle, delta));
    try std.testing.expect(resolution == .local);
    try std.testing.expectEqualStrings(name, index.decls.items[resolution.local].name);
    return resolution.local;
}

fn indexTestContains(index: *const Index, ids: []const u32, name: []const u8) bool {
    for (ids) |id| if (std.mem.eql(u8, index.decls.items[id].name, name)) return true;
    return false;
}

