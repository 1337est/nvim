test "wire: fixed endian header and full-width identifiers" {
    const h: Header = .{ .body_len = 0x10203, .request_id = 0xfeedbeef, .document_id = 70000, .opcode = 5, .flags = 1 };
    const bytes = h.encode();
    try std.testing.expectEqualSlices(u8, &.{ 3, 2, 1, 0, 0xef, 0xbe, 0xed, 0xfe }, bytes[0..8]);
    try std.testing.expectEqualDeep(h, Header.decode(&bytes));
}

test "document: edits are revisioned and preserve the sentinel" {
    var d = try Document.init(std.testing.allocator, 1, 1, "/tmp/t.zig", "const x = 10;\n");
    defer d.deinit();
    _ = try d.ensureIndex();
    try d.edit(1, 2, 10, 2, "200");
    try std.testing.expectEqualStrings("const x = 200;\n", d.source());
    try std.testing.expect(d.ast == null and d.index == null);
    try std.testing.expectEqual(@as(u8, 0), d.bytes.items[d.source().len]);
    try std.testing.expectError(error.StaleRevision, d.edit(1, 2, 0, 0, "wrong"));
    try std.testing.expectError(error.InvalidEdit, d.edit(2, 3, 999, 1, "wrong"));
    try std.testing.expectEqualStrings("const x = 200;\n", d.source());
}

test "document: AST work does not construct the navigation index" {
