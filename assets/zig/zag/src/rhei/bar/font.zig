/// Draw a single character into a 32bpp pixel buffer.
/// pixels: pointer to the buffer's first pixel
/// stride_pixels: number of u32 pixels per row (typically buffer width)
/// buf_width / buf_height: buffer dimensions in pixels (for clipping)
/// x, y: top-left corner of glyph in buffer pixel coords
/// fg: foreground color (XRGB8888 u32)
pub fn drawChar(
    pixels: [*]u32,
    stride_pixels: u32,
    buf_width: u32,
    buf_height: u32,
    x: i32,
    y: i32,
    ch: u8,
    fg: u32,
) void {
    if (ch >= 0x80) return;
    const glyph = &GLYPHS[ch];

    var row: u32 = 0;
    while (row < GLYPH_HEIGHT) : (row += 1) {
        const py: i32 = y + @as(i32, @intCast(row));
        if (py < 0) continue;
        if (py >= @as(i32, @intCast(buf_height))) break;

        const bits = glyph[row];
        var col: u32 = 0;
        while (col < GLYPH_WIDTH) : (col += 1) {
            const px: i32 = x + @as(i32, @intCast(col));
            if (px < 0) continue;
            if (px >= @as(i32, @intCast(buf_width))) break;

            const bit_index: u3 = @intCast(7 - col);
            if ((bits >> bit_index) & 1 != 0) {
                const idx: usize = @as(usize, @intCast(py)) * stride_pixels +
                    @as(usize, @intCast(px));
                pixels[idx] = fg;
            }
        }
    }
}

/// Draw a string starting at (x, y).
pub fn drawText(
    pixels: [*]u32,
    stride_pixels: u32,
    buf_width: u32,
    buf_height: u32,
    x: i32,
    y: i32,
    text: []const u8,
    fg: u32,
) void {
    var px: i32 = x;
    for (text) |ch| {
        drawChar(pixels, stride_pixels, buf_width, buf_height, px, y, ch, fg);
        px += @intCast(GLYPH_WIDTH);
    }
}
